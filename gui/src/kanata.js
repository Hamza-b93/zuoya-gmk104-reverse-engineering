// Generate a Kanata (.kbd) config from the keyboard's physical layout + its
// current layer-0 keymap. Kanata is a host-side remapper (evdev -> uinput), so
// this needs no flashing and works on X11/Wayland, wired or 2.4G.
//
// Pure: keys in, config text out. The GUI supplies `keys` (each {x, y, code})
// built from the VIA layout + a keymap read; this module maps HID keycodes to
// Kanata key names and lays out aligned `defsrc` / `deflayer` blocks.

// HID usage (low byte of a VIA keycode) -> Kanata/evdev key name.
const NAMES = (() => {
  const m = {
    0x28: 'ret', 0x29: 'esc', 0x2a: 'bspc', 0x2b: 'tab', 0x2c: 'spc',
    0x2d: 'min', 0x2e: 'eql', 0x2f: 'lbrc', 0x30: 'rbrc', 0x31: 'bksl',
    0x33: 'scln', 0x34: 'apos', 0x35: 'grv', 0x36: 'comm', 0x37: 'dot', 0x38: 'slsh',
    0x39: 'caps', 0x46: 'prnt', 0x47: 'slck', 0x48: 'pause',
    0x49: 'ins', 0x4a: 'home', 0x4b: 'pgup', 0x4c: 'del', 0x4d: 'end', 0x4e: 'pgdn',
    0x4f: 'rght', 0x50: 'left', 0x51: 'down', 0x52: 'up',
    0x53: 'nlck', 0x54: 'kp/', 0x55: 'kp*', 0x56: 'kp-', 0x57: 'kp+', 0x58: 'kprt',
    0x63: 'kp.', 0x65: 'cmp',
    0xe0: 'lctl', 0xe1: 'lsft', 0xe2: 'lalt', 0xe3: 'lmet',
    0xe4: 'rctl', 0xe5: 'rsft', 0xe6: 'ralt', 0xe7: 'rmet',
    // Consumer/media (classic QMK keycode values, as VIA writes them).
    0xa8: 'mute', 0xa9: 'volu', 0xaa: 'vold',
    0xab: 'next', 0xac: 'prev', 0xad: 'stop', 0xae: 'pp',
  };
  for (let i = 0; i < 26; i++) m[0x04 + i] = String.fromCharCode(97 + i); // a-z
  for (let i = 0; i < 9; i++) m[0x1e + i] = String(i + 1); // 1-9
  m[0x27] = '0';
  for (let i = 0; i < 12; i++) m[0x3a + i] = `f${i + 1}`; // F1-F12
  for (let i = 0; i < 9; i++) m[0x59 + i] = `kp${i + 1}`; // KP1-KP9
  m[0x62] = 'kp0';
  return m;
})();

// Kanata name for a 16-bit VIA keycode, or null if we can't map it (layer/macro/
// custom codes, which Kanata expresses differently and shouldn't be guessed).
export function hidToKanata(code) {
  return NAMES[code & 0xffff] ?? (code <= 0xff ? NAMES[code] : null) ?? null;
}

// Group keys into physical rows (sorted top-to-bottom, left-to-right).
function toRows(keys) {
  const sorted = [...keys].sort((a, b) => a.y - b.y || a.x - b.x);
  const rows = [];
  let cur = null;
  for (const k of sorted) {
    if (!cur || Math.abs(k.y - cur.y) > 0.4) {
      cur = { y: k.y, items: [] };
      rows.push(cur);
    }
    cur.items.push(k);
  }
  return rows;
}

// Build the config. Returns { config, mapped, skipped } where `skipped` lists
// physical keys we couldn't map (duplicates or non-basic codes) — those simply
// pass through to the OS, unmanaged by Kanata.
export function generateKanataConfig(keys, { name = 'ZUOYA GMK104' } = {}) {
  const skipped = [];
  const seen = new Set();
  const rows = toRows(keys).map((row) => {
    const toks = [];
    for (const k of row.items) {
      const kn = hidToKanata(k.code);
      if (!kn) { skipped.push({ ...k, reason: 'unmapped code' }); continue; }
      if (seen.has(kn)) { skipped.push({ ...k, reason: `duplicate ${kn}` }); continue; }
      seen.add(kn);
      toks.push(kn);
    }
    return toks;
  }).filter((r) => r.length);

  const pad = Math.max(4, ...[...seen].map((n) => n.length)) + 1;
  const fmt = (toks) => '  ' + toks.map((t) => t.padEnd(pad)).join('').trimEnd();
  const block = rows.map(fmt).join('\n');

  const header =
    `;; Kanata config generated by Keeb Control for "${name}".\n` +
    `;; Host-side remapping — no flashing. Run it with:\n` +
    `;;     kanata --cfg this-file.kbd\n` +
    `;; (needs the kanata binary + access to /dev/uinput).\n` +
    `;;\n` +
    `;; 'defsrc' is your physical keyboard; 'deflayer base' is what each key\n` +
    `;; does. They start identical (a no-op) — edit 'base', or add layers and\n` +
    `;; aliases below. Docs: https://github.com/jtroo/kanata\n`;

  const example =
    `\n;; --- Example: hold Caps Lock for a nav layer (uncomment + adapt) ---\n` +
    `;; (defalias\n` +
    `;;   cap (tap-hold 200 200 caps (layer-while-held nav)))\n` +
    `;; Put @cap where 'caps' is in 'base', then add:\n` +
    `;; (deflayer nav\n` +
    `;;   ... same number of tokens as defsrc; use _ to pass a key through ...\n` +
    `;; )\n`;

  const skippedNote = skipped.length
    ? `\n;; Not managed by Kanata (passed through unchanged): ` +
      skipped.map((s) => `${s.reason}@${s.row},${s.col}`).join(', ') + '\n'
    : '';

  const config =
    header +
    `\n(defsrc\n${block}\n)\n` +
    `\n(deflayer base\n${block}\n)\n` +
    example +
    skippedNote;

  return { config, mapped: seen.size, skipped };
}
